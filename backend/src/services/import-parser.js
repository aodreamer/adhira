const ExcelJS = require('exceljs');
const Joi = require('joi');
const { PANGKAT_OPTIONS } = require('../validators/rank-data');
const { PROVINCES, REGENCIES } = require('../validators/wilayah-data');

const PEMDA_TIPE_OPTIONS = ['Pemerintah Provinsi', 'Pemerintah Kabupaten', 'Pemerintah Kota'];
const PEMDA_TIPE_ALIASES = { provinsi: 'Pemerintah Provinsi', kabupaten: 'Pemerintah Kabupaten', kota: 'Pemerintah Kota' };
const PROVINCE_NAMES = PROVINCES.map((p) => p.name);
const REGENCY_NAMES = REGENCIES.map((r) => r.name);

const MAX_ROWS = 500;

// Header label (shown in the downloadable template) -> row field key.
// Matched by label text, not column position, so a Dewan reordering columns
// in Excel doesn't break parsing.
const COLUMNS = [
  { header: 'Nama Lengkap', key: 'nama', required: true },
  { header: 'NIP/NRP', key: 'nipnrp', required: true },
  { header: 'Email', key: 'email', required: true },
  { header: 'No HP', key: 'hp', required: false },
  { header: 'Jabatan', key: 'jabatan', required: true },
  { header: 'Unit Kerja', key: 'unit_kerja', required: false },
  { header: 'Pangkat/Golongan', key: 'pangkat', required: true },
  { header: 'Jenis Penghargaan', key: 'jenis_penghargaan', required: true },
  { header: 'TMT CPNS/PNS (YYYY-MM-DD)', key: 'tgl_tmt_cpns_pns', required: false },
  { header: 'Masa Kerja Kumulatif Tahun', key: 'masa_kerja_kumulatif_tahun', required: false },
  { header: 'Masa Kerja Kumulatif Bulan', key: 'masa_kerja_kumulatif_bulan', required: false },
  { header: 'Masa Kerja Pengurangan Tahun', key: 'masa_kerja_pengurangan_tahun', required: false },
  { header: 'Masa Kerja Pengurangan Bulan', key: 'masa_kerja_pengurangan_bulan', required: false },
  { header: 'Tipe Pemda (Provinsi/Kabupaten/Kota)', key: 'pemda_tipe', required: false },
  { header: 'Provinsi', key: 'pemda_provinsi', required: false },
  { header: 'Kabupaten/Kota', key: 'pemda_kabkota', required: false },
];

function toIntOrNull(v) {
  return v === '' || v === null || v === undefined ? null : Number(v);
}

function cellToString(value) {
  if (value === null || value === undefined) return '';
  if (value instanceof Date) return value.toISOString().split('T')[0];
  if (typeof value === 'object') {
    if (typeof value.text === 'string') return value.text.trim();
    if (Array.isArray(value.richText)) return value.richText.map((rt) => rt.text).join('').trim();
    if (value.result !== undefined) return cellToString(value.result);
    return '';
  }
  return String(value).trim();
}

// Scans the first few rows for the one whose cells best match our known
// header labels — tolerates an instruction/title row above the real header
// (as generated by generateTemplateWorkbook) without hardcoding a row index.
function findHeaderRow(sheet) {
  let best = { rowIndex: 1, matches: 0, map: {} };
  for (let r = 1; r <= Math.min(5, sheet.rowCount); r++) {
    const row = sheet.getRow(r);
    const map = {};
    let matches = 0;
    row.eachCell({ includeEmpty: false }, (cell, colNumber) => {
      // Required headers are generated with a trailing " *" marker (see
      // generateTemplateWorkbook) — strip it before comparing.
      const label = cellToString(cell.value).toLowerCase().replace(/\s*\*\s*$/, '');
      const match = COLUMNS.find((c) => c.header.toLowerCase() === label);
      if (match) { map[match.key] = colNumber; matches++; }
    });
    if (matches > best.matches) best = { rowIndex: r, matches, map };
  }
  return best;
}

function normalizePemdaTipe(raw) {
  const out = { ...raw };
  if (out.pemda_tipe) {
    const alias = PEMDA_TIPE_ALIASES[out.pemda_tipe.trim().toLowerCase()];
    if (alias) out.pemda_tipe = alias;
  }
  return out;
}

// instansi is the batch's fixed instansi (chosen by the uploading Verifikator,
// not a template column) — it determines whether the pemda_* fields are
// required, exactly mirroring selfProfileSchema's instansi-conditional rules.
function rowSchema(instansi) {
  const isPemda = instansi === 'Pemerintah Daerah';
  const pemdaField = (allowedValues, label) => {
    const base = Joi.string().valid(...allowedValues, '').messages({ 'any.only': label + ' tidak dikenali' });
    return isPemda
      ? base.invalid('').required().messages({
          'any.required': label + ' wajib diisi untuk instansi Pemerintah Daerah',
          'any.invalid': label + ' wajib diisi untuk instansi Pemerintah Daerah',
          'any.only': label + ' tidak dikenali',
        })
      : base.allow(null).optional();
  };

  return Joi.object({
    nama: Joi.string().trim().min(3).max(255).required().messages({
      'string.min': 'Nama minimal 3 karakter', 'any.required': 'Nama wajib diisi', 'string.empty': 'Nama wajib diisi',
    }),
    nipnrp: Joi.string().trim().min(3).max(255).required().messages({
      'any.required': 'NIP/NRP wajib diisi', 'string.empty': 'NIP/NRP wajib diisi',
    }),
    email: Joi.string().trim().email({ tlds: false }).required().messages({
      'string.email': 'Format email tidak valid', 'any.required': 'Email wajib diisi', 'string.empty': 'Email wajib diisi',
    }),
    hp: Joi.string().trim().max(50).allow('', null),
    jabatan: Joi.string().trim().min(2).max(255).required().messages({
      'string.min': 'Jabatan minimal 2 karakter', 'any.required': 'Jabatan wajib diisi', 'string.empty': 'Jabatan wajib diisi',
    }),
    unit_kerja: Joi.string().trim().max(255).allow('', null),
    pangkat: Joi.string().valid(...PANGKAT_OPTIONS).required().messages({
      'any.only': 'Pangkat/golongan tidak dikenali', 'any.required': 'Pangkat/golongan wajib diisi', 'string.empty': 'Pangkat/golongan wajib diisi',
    }),
    jenis_penghargaan: Joi.string().trim().min(2).max(255).required().messages({
      'any.required': 'Jenis penghargaan wajib diisi', 'string.empty': 'Jenis penghargaan wajib diisi',
    }),
    tgl_tmt_cpns_pns: Joi.date().allow('', null).messages({ 'date.base': 'Format tanggal TMT CPNS/PNS tidak valid (gunakan YYYY-MM-DD)' }),
    masa_kerja_kumulatif_tahun: Joi.number().integer().min(0).allow('', null).messages({ 'number.base': 'Masa kerja kumulatif tahun harus angka' }),
    masa_kerja_kumulatif_bulan: Joi.number().integer().min(0).max(11).allow('', null).messages({ 'number.base': 'Masa kerja kumulatif bulan harus angka' }),
    masa_kerja_pengurangan_tahun: Joi.number().integer().min(0).allow('', null).messages({ 'number.base': 'Masa kerja pengurangan tahun harus angka' }),
    masa_kerja_pengurangan_bulan: Joi.number().integer().min(0).max(11).allow('', null).messages({ 'number.base': 'Masa kerja pengurangan bulan harus angka' }),
    pemda_tipe: pemdaField(PEMDA_TIPE_OPTIONS, 'Tipe pemda'),
    pemda_provinsi: pemdaField(PROVINCE_NAMES, 'Provinsi'),
    pemda_kabkota: pemdaField(REGENCY_NAMES, 'Kabupaten/Kota'),
  });
}

async function parseTemplateBuffer(buffer, instansi) {
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.load(buffer);
  const sheet = workbook.worksheets[0];
  if (!sheet) return { headerErrors: ['File tidak berisi sheet apapun'], rows: [] };

  const { rowIndex: headerRowIdx, matches, map: colIndexByKey } = findHeaderRow(sheet);
  if (matches === 0) return { headerErrors: ['Header kolom tidak dikenali. Gunakan template resmi (unduh dari tombol "Unduh Template").'], rows: [] };

  const missingRequired = COLUMNS.filter((c) => c.required && !colIndexByKey[c.key]);
  if (missingRequired.length > 0) {
    return { headerErrors: missingRequired.map((c) => `Kolom wajib "${c.header}" tidak ditemukan di baris header`), rows: [] };
  }

  const rawRows = [];
  for (let r = headerRowIdx + 1; r <= sheet.rowCount; r++) {
    const row = sheet.getRow(r);
    const raw = {};
    for (const col of COLUMNS) {
      const idx = colIndexByKey[col.key];
      raw[col.key] = idx ? cellToString(row.getCell(idx).value) : '';
    }
    if (Object.values(raw).every((v) => v === '')) continue;
    rawRows.push(raw);
  }

  if (rawRows.length === 0) return { headerErrors: ['Tidak ada baris data untuk diproses'], rows: [] };
  if (rawRows.length > MAX_ROWS) {
    return { headerErrors: [`Maksimal ${MAX_ROWS} baris data per file (ditemukan ${rawRows.length} baris)`], rows: [] };
  }

  const schema = rowSchema(instansi);
  const rows = rawRows.map((raw, i) => {
    const normalized = normalizePemdaTipe(raw);
    const { error, value } = schema.validate(normalized, { abortEarly: false, stripUnknown: true });
    const errors = (error?.details || []).map((d) => ({ field: d.path[0], message: d.message }));

    if (!error && value.pemda_kabkota) {
      const regency = REGENCIES.find((rg) => rg.name === value.pemda_kabkota);
      if (regency) {
        if (value.pemda_provinsi && regency.provinceName !== value.pemda_provinsi) {
          errors.push({ field: 'pemda_kabkota', message: 'Kabupaten/Kota tidak sesuai dengan provinsi yang dipilih' });
        }
        if (value.pemda_tipe && 'Pemerintah ' + regency.type !== value.pemda_tipe) {
          errors.push({ field: 'pemda_kabkota', message: 'Kabupaten/Kota tidak sesuai dengan tipe pemda yang dipilih' });
        }
      }
    }

    return {
      row_number: i + 1,
      nama: value.nama ?? raw.nama,
      nipnrp: value.nipnrp ?? raw.nipnrp,
      email: (value.email ?? raw.email ?? '').toLowerCase(),
      hp: value.hp || '',
      jabatan: value.jabatan ?? raw.jabatan,
      unit_kerja: value.unit_kerja || '',
      pangkat: value.pangkat ?? raw.pangkat,
      jenis_penghargaan: value.jenis_penghargaan ?? raw.jenis_penghargaan,
      tgl_tmt_cpns_pns: value.tgl_tmt_cpns_pns ? new Date(value.tgl_tmt_cpns_pns).toISOString().split('T')[0] : null,
      masa_kerja_kumulatif_tahun: toIntOrNull(value.masa_kerja_kumulatif_tahun),
      masa_kerja_kumulatif_bulan: toIntOrNull(value.masa_kerja_kumulatif_bulan),
      masa_kerja_pengurangan_tahun: toIntOrNull(value.masa_kerja_pengurangan_tahun),
      masa_kerja_pengurangan_bulan: toIntOrNull(value.masa_kerja_pengurangan_bulan),
      pemda_tipe: value.pemda_tipe || '',
      pemda_provinsi: value.pemda_provinsi || '',
      pemda_kabkota: value.pemda_kabkota || '',
      row_status: errors.length > 0 ? 'Error' : 'Valid',
      errors,
    };
  });

  return { headerErrors: [], rows };
}

async function generateTemplateWorkbook() {
  const workbook = new ExcelJS.Workbook();
  const sheet = workbook.addWorksheet('Usulan');

  sheet.mergeCells(1, 1, 1, COLUMNS.length);
  const note = sheet.getCell(1, 1);
  note.value = 'Kolom bertanda * wajib diisi. Tipe Pemda/Provinsi/Kabupaten-Kota wajib diisi khusus untuk instansi Pemerintah Daerah. Jangan ubah baris header (baris 2).';
  note.font = { italic: true, size: 10, color: { argb: 'FF6B7280' } };

  const headerRow = sheet.getRow(2);
  COLUMNS.forEach((c, i) => {
    const cell = headerRow.getCell(i + 1);
    cell.value = c.header + (c.required ? ' *' : '');
    cell.font = { bold: true };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFE5E7EB' } };
  });
  sheet.columns.forEach((col) => { col.width = 26; });

  const ref = workbook.addWorksheet('Referensi Pangkat');
  ref.getCell(1, 1).value = 'Pangkat/Golongan yang valid';
  ref.getCell(1, 1).font = { bold: true };
  ref.getColumn(1).width = 42;
  PANGKAT_OPTIONS.forEach((p, i) => { ref.getCell(i + 2, 1).value = p; });

  return workbook.xlsx.writeBuffer();
}

module.exports = { parseTemplateBuffer, generateTemplateWorkbook, rowSchema, COLUMNS, MAX_ROWS };
